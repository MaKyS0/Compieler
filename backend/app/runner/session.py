"""One interactive job session: install -> compile -> run pipeline for a project.

A ``JobSession`` belongs to one WebSocket connection and runs at most one job at a
time. It translates language specific workflows into sandbox commands, streams their
output through ``emit`` and always finishes a job with exactly one ``exit`` event.
"""
from __future__ import annotations

import asyncio
import hashlib
import json
import logging
import re
import shlex
from collections.abc import Awaitable, Callable
from dataclasses import dataclass
from pathlib import PurePosixPath

from ..config import Settings
from ..sandbox.base import ExecRequest, ExecResult, Limits, ManagedProcess, Sandbox
from ..services.projectfs import FSError, ProjectFS, split_path
from . import diagnostics

log = logging.getLogger("compieler.runner")

Emit = Callable[[dict], Awaitable[None]]

CPP_STANDARDS = ("c++17", "c++20", "c++23")
CPP_EXT = (".cpp", ".cc", ".cxx", ".c++")
CPP_OPT = ("-O0", "-O1", "-O2", "-O3")
DEFAULT_ENTRY = {"python": "main.py", "cpp": "main.cpp", "javascript": "index.js"}
PKG_SPEC = re.compile(r"^[A-Za-z0-9@][A-Za-z0-9@._/\-\[\],<>=!~^*+:]*$")
NET_COMMANDS = {"pip", "pip3", "npm", "npx", "yarn", "pnpm"}

HOOK_SOURCE = b"""// Generated by Compieler: unbuffer stdout when the program is interactive so that
// prompts written with printf() appear before scanf() blocks on stdin.
#include <cstdio>
#include <cstdlib>
__attribute__((constructor)) static void compieler_unbuffer_stdout() {
  if (std::getenv("COMPIELER_UNBUFFERED")) std::setvbuf(stdout, nullptr, _IONBF, 0);
}
"""


NODE_HOOK = b"""// Generated by Compieler. With a pipe on stdin (no TTY) Node keeps the event loop alive
// after readline.close() / stdin.pause(), so programs that finish reading would never exit.
// Mirror TTY behaviour: a paused stdin does not keep the process running.
const desc = Object.getOwnPropertyDescriptor(process, 'stdin');
if (desc && desc.get) {
  let stream;
  Object.defineProperty(process, 'stdin', {
    configurable: true, enumerable: true,
    get() {
      if (!stream) {
        stream = desc.get.call(process);
        const h = stream && stream._handle;
        if (h && typeof h.unref === 'function') {
          const sync = () => { try { stream.isPaused() ? h.unref() : h.ref(); } catch (_) {} };
          stream.on('pause', sync); stream.on('resume', sync);
        }
      }
      return stream;
    },
  });
}
"""


@dataclass
class ProjectCtx:
    id: int
    language: str
    settings: dict
    fs: ProjectFS


class JobError(Exception):
    """A pipeline step failed in a way the user should be told about."""


class _Aborted(Exception):
    """A prerequisite phase (install) failed; carries the final result."""

    def __init__(self, result: ExecResult, phase: str):
        self.result, self.phase = result, phase


def _sha(*chunks: bytes) -> str:
    h = hashlib.sha256()
    for c in chunks:
        h.update(len(c).to_bytes(8, "big"))
        h.update(c)
    return h.hexdigest()


class JobSession:
    def __init__(self, sandbox: Sandbox, settings: Settings, project: ProjectCtx, emit: Emit):
        self.sbx = sandbox
        self.s = settings
        self.p = project
        self.emit = emit
        self.workdir = sandbox.workdir(project.id, project.fs.root)
        self.cache = sandbox.cache_path(project.id, project.fs.root)
        self._current: ManagedProcess | None = None
        self._busy = False
        self._stop = False
        self._accepts_stdin = False
        self._done = False
        # Input that arrives before the program exists (typed during install/compile,
        # or sent in the same breath as "run") is held here and delivered on start.
        self._pending: list[str | None] = []

    # ------------------------------------------------------------------ public
    @property
    def busy(self) -> bool:
        return self._busy

    async def send_stdin(self, data: str) -> None:
        if self._current and self._accepts_stdin:
            await self._current.write_stdin(data.encode("utf-8", "replace"))
        elif not self._done and len(self._pending) < 10_000:
            self._pending.append(data)

    async def close_stdin(self) -> None:
        if self._current and self._accepts_stdin:
            await self._current.close_stdin()
        elif not self._done:
            self._pending.append(None)  # EOF marker

    async def stop(self) -> None:
        self._stop = True
        if self._current:
            await self._current.stop("stopped")

    async def run(self, cfg: dict) -> None:
        await self._job("run", self._run_pipeline(cfg))

    async def shell(self, command: str) -> None:
        await self._job("shell", self._shell_pipeline(command))

    async def install(self, packages: list[str]) -> None:
        await self._job("install", self._install_pipeline(packages))

    # ------------------------------------------------------------------ job wrapper
    async def _job(self, kind: str, coro) -> None:
        if self._busy:
            coro.close()
            await self.emit({"type": "error", "code": "busy", "message": "A program is already running."})
            return
        self._busy = True  # a stop() that arrived while queued must survive: sessions are single-use
        await self.emit({"type": "start", "kind": kind})
        await self.emit({"type": "problems", "items": []})
        result: ExecResult | None = None
        phase = kind
        try:
            if self._stop:
                coro.close()
                result = ExecResult(None, None, "stopped", 0)
            else:
                result, phase = await coro
        except _Aborted as a:
            result, phase = a.result, a.phase
        except JobError as e:
            await self._system(f"{e}\n", "stderr")
            result = ExecResult(None, None, "error", 0, str(e))
        except FSError as e:
            await self._system(f"{e.message}\n", "stderr")
            result = ExecResult(None, None, "error", 0, e.message)
        except Exception as e:  # noqa: BLE001
            log.exception("job failed")
            await self._system("Internal error while starting the program. The details were logged on the server.\n", "stderr")
            result = ExecResult(None, None, "sandbox_error", 0, type(e).__name__)
        finally:
            self._current = None
            self._busy = False
            self._done = True
        reason = result.reason
        if self._stop and reason in ("error", "signal", "ok"):
            reason = "stopped"
        if reason == "error" and phase == "compile":
            reason = "compile_error"
        elif reason == "error" and phase == "install":
            reason = "install_failed"
        await self.emit(
            {
                "type": "exit",
                "kind": kind,
                "phase": phase,
                "code": result.exit_code,
                "signal": result.signal,
                "reason": reason,
                "duration_ms": result.duration_ms,
                "detail": result.detail,
            }
        )

    async def _system(self, text: str, stream: str = "system") -> None:
        await self.emit({"type": "output", "phase": "system", "stream": stream, "data": text})

    # ------------------------------------------------------------------ limits / env
    def _limits(self, phase: str, cfg: dict | None = None) -> Limits:
        s, cfg = self.s, cfg or {}
        if phase == "run":
            wall = min(float(cfg.get("timeout") or s.run_wall_seconds), s.run_wall_seconds)
            cpu = min(float(cfg.get("cpu_limit") or s.run_cpu_seconds), s.run_cpu_seconds)
            mem = min(int(cfg.get("memory_mb") or s.memory_mb), s.memory_mb)
            return Limits(max(wall, 1), max(cpu, 1), max(mem, 32), s.max_processes, s.max_file_write_mb,
                          s.max_open_files, s.max_output_bytes,
                          vm_factor={"cpp": 2.0, "python": 8.0}.get(self.p.language))
        if phase == "compile":
            return Limits(s.compile_wall_seconds, s.compile_wall_seconds, max(1024, s.memory_mb), 256,
                          s.max_file_write_mb * 4, 1024, 2_000_000)
        # install / shell
        return Limits(s.install_wall_seconds, s.install_wall_seconds, max(1536, s.memory_mb), 512,
                      s.max_file_write_mb * 8, 4096, 4_000_000)

    def _env(self, extra: dict | None = None) -> dict[str, str]:
        wd = self.workdir
        path = [f"{wd}/.venv/bin", f"{wd}/node_modules/.bin", self.sbx.default_path()]
        env = {
            "PATH": ":".join(path),
            "LANG": "C.UTF-8",
            "LC_ALL": "C.UTF-8",
            "TERM": "xterm-256color",
            "PYTHONUNBUFFERED": "1",
            "PYTHONDONTWRITEBYTECODE": "1",
            "PYTHONIOENCODING": "utf-8",
            "PYTHONNOUSERSITE": "1",
            "MPLBACKEND": "Agg",
            "OPENBLAS_NUM_THREADS": "1",
            "OMP_NUM_THREADS": "1",
            "PIP_DISABLE_PIP_VERSION_CHECK": "1",
            "PIP_NO_INPUT": "1",
            "PIP_CACHE_DIR": f"{self.cache}/pip",
            "npm_config_cache": f"{self.cache}/npm",
            "npm_config_update_notifier": "false",
            "npm_config_fund": "false",
            "npm_config_audit": "false",
        }
        if extra:
            env.update(extra)
        return env

    # ------------------------------------------------------------------ exec
    async def _exec(
        self,
        phase: str,
        argv: list[str],
        limits: Limits,
        *,
        env_extra: dict | None = None,
        network: str = "none",
        stdin: str | None = None,
        close_stdin: bool = False,
    ) -> tuple[ExecResult, str]:
        """Run one sandboxed command; returns its result and a tail of its output."""
        tail: list[str] = []
        tail_len = 0

        async def on_output(stream: str, text: str) -> None:
            nonlocal tail_len
            if tail_len < 200_000:
                tail.append(text if stream == "stderr" or phase != "run" else "")
                tail_len += len(text)
            await self.emit({"type": "output", "phase": phase, "stream": stream, "data": text})

        env = self._env(env_extra)
        if network != "none":
            env.update(self.s.install_env)
        req = ExecRequest(
            project_id=self.p.id,
            project_dir=self.p.fs.root,
            argv=argv,
            env=env,
            limits=limits,
            network=network,
            phase=phase,
        )
        mp = ManagedProcess(self.sbx, req, on_output)
        await mp.start()
        self._current = mp
        if self._stop:  # stop arrived while spawning
            await mp.stop("stopped")
        try:
            if stdin:
                await mp.write_stdin(stdin.encode("utf-8", "replace"))
            if close_stdin:
                await mp.close_stdin()
            if phase in ("run", "shell"):
                pending, self._pending = self._pending, []
                for item in pending:
                    if item is None:
                        await mp.close_stdin()
                    else:
                        await mp.write_stdin(item.encode("utf-8", "replace"))
                self._accepts_stdin = True
            result = await mp.wait()
        finally:
            self._current = None
            self._accepts_stdin = False
        return result, "".join(tail)

    # ------------------------------------------------------------------ helpers
    def _entry(self, cfg: dict) -> str:
        entry = cfg.get("entry") or self.p.settings.get("entry") or DEFAULT_ENTRY[self.p.language]
        parts = split_path(entry)
        entry = "/".join(parts)
        if self.p.fs.exists(entry) != "file":
            raise JobError(f"Entry file '{entry}' does not exist. Create it or choose another file to run.")
        return entry

    @staticmethod
    def _args(cfg: dict) -> list[str]:
        raw = cfg.get("args") or ""
        if isinstance(raw, list):
            return [str(a) for a in raw][:64]
        try:
            return shlex.split(str(raw))[:64]
        except ValueError as e:
            raise JobError(f"Cannot parse program arguments: {e}") from e

    def _read_hidden(self, rel: str) -> bytes | None:
        try:
            return self.p.fs.read(rel, allow_hidden=True)
        except FSError:
            return None

    def _write_hidden(self, rel: str, data: bytes) -> None:
        self.p.fs.write(rel, data, allow_hidden=True)

    async def _finish_phase(self, phase: str, result: ExecResult, text: str) -> None:
        """Emit problems / hints after a phase finished unsuccessfully (or compiled with warnings)."""
        lang = self.p.language
        items: list[diagnostics.Problem] = []
        if phase == "compile":
            items = diagnostics.parse_gcc(text, self.workdir)
        elif phase == "run" and result.reason == "error":
            parser = {"python": diagnostics.parse_python, "javascript": diagnostics.parse_node}.get(lang)
            if parser:
                items = parser(text, self.workdir)
        if items:
            await self.emit({"type": "problems", "items": [i.as_dict() for i in items], "phase": phase})
        if result.reason == "error":
            for h in diagnostics.hints_for(lang, text, phase, result.reason):
                await self._system(f"\n[hint] {h}\n")
        if result.reason in ("timeout", "memory", "output_limit", "cpu_limit"):
            await self._system(f"\n[{result.detail or result.reason}]\n", "stderr")

    # ------------------------------------------------------------------ pipelines
    async def _run_pipeline(self, cfg: dict):
        lang = self.p.language
        entry = self._entry(cfg)
        args = self._args(cfg)
        stdin_text = cfg.get("stdin") or ""
        interactive = not stdin_text
        network = "none"
        if cfg.get("network"):
            if self.s.allow_runtime_network:
                network = "full"
            else:
                await self._system("[network access at run time is disabled on this server]\n", "stderr")

        if lang == "python":
            await self._python_prepare()
            if self._stop:
                return ExecResult(None, None, "stopped", 0), "install"
            venv = self.p.fs.exists(".venv") == "dir"
            py = f"{self.workdir}/.venv/bin/python" if venv else "python3"
            argv = [py, "-u", "-X", "utf8", entry, *args]
        elif lang == "javascript":
            await self._node_prepare()
            if self._stop:
                return ExecResult(None, None, "stopped", 0), "install"
            heap = max(32, int(self._limits("run", cfg).memory_mb * 0.75))
            self._write_hidden(".compieler/node-hook.js", NODE_HOOK)
            argv = ["node", f"--max-old-space-size={heap}", "--require", "./.compieler/node-hook.js", entry, *args]
        elif lang == "cpp":
            res = await self._cpp_compile(cfg, entry)
            if res is not None:
                return res, "compile"
            argv = [f"{self.workdir}/.compieler/build/app", *args]
        else:
            raise JobError(f"Unsupported language: {lang}")

        if self._stop:
            return ExecResult(None, None, "stopped", 0), "run"
        limits = self._limits("run", cfg)
        extra = {"COMPIELER_UNBUFFERED": "1"} if interactive else {}
        result, text = await self._exec(
            "run", argv, limits, env_extra=extra, network=network, stdin=stdin_text or None,
            close_stdin=bool(stdin_text),
        )
        await self._finish_phase("run", result, text)
        return result, "run"

    # --- python ------------------------------------------------------------
    async def _python_prepare(self) -> None:
        fs = self.p.fs
        req = self._read_hidden("requirements.txt")
        effective = [ln for ln in (req or b"").decode("utf-8", "replace").splitlines() if ln.strip() and not ln.lstrip().startswith("#")]
        if req is None or not effective:
            return
        digest = _sha(req)
        if self._read_hidden(".compieler/req.sha") == digest.encode() and fs.exists(".venv") == "dir":
            return
        await self._system("Installing requirements.txt ...\n")
        script = (
            "set -e\n"
            "[ -d .venv ] || python3 -m venv --system-site-packages .venv\n"
            ".venv/bin/python -m pip install --no-input --disable-pip-version-check -r requirements.txt\n"
        )
        result, text = await self._exec("install", ["bash", "-c", script], self._limits("install"), network="install")
        await self._finish_phase("install", result, text)
        if result.reason != "ok":
            raise _Aborted(result, "install")
        self._write_hidden(".compieler/req.sha", digest.encode())
        await self._system("Requirements installed.\n\n")

    # --- node --------------------------------------------------------------
    async def _node_prepare(self) -> None:
        fs = self.p.fs
        pkg = self._read_hidden("package.json")
        if pkg is None:
            return
        try:
            meta = json.loads(pkg or b"{}")
        except json.JSONDecodeError as e:
            raise JobError(f"package.json is not valid JSON: {e}") from e
        deps = {**(meta.get("dependencies") or {}), **(meta.get("devDependencies") or {})}
        if not deps:
            return
        lock = self._read_hidden("package-lock.json") or b""
        digest = _sha(pkg, lock)
        if self._read_hidden(".compieler/pkg.sha") == digest.encode() and fs.exists("node_modules") == "dir":
            return
        await self._system("Installing npm dependencies ...\n")
        cmd = "npm ci" if lock else "npm install"
        script = f"{cmd} --no-audit --no-fund --no-progress --loglevel=error"
        result, text = await self._exec("install", ["bash", "-c", script], self._limits("install"), network="install")
        await self._finish_phase("install", result, text)
        if result.reason != "ok":
            raise _Aborted(result, "install")
        # npm may rewrite package-lock.json; hash the post-install state.
        self._write_hidden(".compieler/pkg.sha", _sha(self._read_hidden("package.json") or b"", self._read_hidden("package-lock.json") or b"").encode())
        await self._system("Dependencies installed.\n\n")

    # --- c++ ---------------------------------------------------------------
    def _cpp_sources(self, entry: str) -> list[str]:
        files = [e.path for e in self.p.fs.tree(max_entries=20_000) if e.type == "file" and e.path.lower().endswith(CPP_EXT)]
        if not files:
            raise JobError("No C++ source files (.cpp, .cc, .cxx) found in the project.")
        mains = [f for f in files if re.search(rb"\bmain\s*\(", self.p.fs.read(f, allow_hidden=False))]
        if len(mains) > 1:
            # Several programs in one project: build the selected one plus helper files.
            files = [f for f in files if f not in mains or f == entry]
            if entry not in files:
                files.append(entry)
        return sorted(files)

    async def _cpp_compile(self, cfg: dict, entry: str) -> ExecResult | None:
        """Compile; returns a result only when compilation failed or was stopped."""
        st = self.p.settings
        std = cfg.get("std") or st.get("cpp_std") or "c++17"
        if std not in CPP_STANDARDS:
            raise JobError(f"Unsupported C++ standard '{std}'. Choose one of: {', '.join(CPP_STANDARDS)}.")
        opt = cfg.get("opt") or st.get("cpp_opt") or "-O2"
        if opt not in CPP_OPT:
            opt = "-O2"
        sources = self._cpp_sources(entry)
        contents = [(f, self.p.fs.read(f)) for f in sources]
        headers = [
            (e.path, self.p.fs.read(e.path)) for e in self.p.fs.tree(max_entries=20_000)
            if e.type == "file" and e.path.lower().endswith((".h", ".hpp", ".hh", ".hxx", ".inl", ".tpp"))
        ]
        digest = _sha(std.encode(), opt.encode(), *[x for f, c in contents + headers for x in (f.encode(), c)])
        binary = ".compieler/build/app"
        if self._read_hidden(".compieler/build/hash") == digest.encode() and self.p.fs.exists(binary) == "file":
            await self._system("(using cached build)\n")
            return None
        self._write_hidden(".compieler/hook.cpp", HOOK_SOURCE)
        self._write_hidden(".compieler/build/.keep", b"")
        argv = ["g++", f"-std={std}", opt, "-Wall", "-Wextra", "-pipe", "-fno-diagnostics-color", "-I.",
                *sources, ".compieler/hook.cpp", "-o", binary]
        await self._system(f"$ g++ -std={std} {opt} {' '.join(sources)}\n")
        result, text = await self._exec("compile", argv, self._limits("compile"))
        await self._finish_phase("compile", result, text)
        if result.reason != "ok":
            return result
        self._write_hidden(".compieler/build/hash", digest.encode())
        return None

    # --- shell / install ----------------------------------------------------
    def _shell_prelude(self) -> str:
        lang = self.p.language
        if lang == "python":
            return "[ -d .venv ] || python3 -m venv --system-site-packages .venv >/dev/null 2>&1\n"
        return ""

    async def _shell_pipeline(self, command: str):
        command = command.strip()
        if not command or len(command) > 4000 or "\x00" in command:
            raise JobError("Invalid command.")
        first = command.split()[0] if command.split() else ""
        net = "install" if first in NET_COMMANDS or re.match(r"^python3?\s+-m\s+pip\b", command) else "none"
        script = self._shell_prelude() + command
        phase = "install" if net == "install" else "shell"
        result, text = await self._exec(phase, ["bash", "-c", script], self._limits("install"), network=net)
        if net == "install":
            await self._finish_phase("install", result, text)
        return result, phase

    async def _install_pipeline(self, packages: list[str]):
        pkgs = [p.strip() for p in packages if p and p.strip()]
        if not pkgs:
            raise JobError("No packages given.")
        if len(pkgs) > 30:
            raise JobError("Too many packages in one request.")
        for p in pkgs:
            if not PKG_SPEC.match(p) or len(p) > 120 or p.startswith("-"):
                raise JobError(f"'{p}' is not a valid package specifier.")
        quoted = " ".join(shlex.quote(p) for p in pkgs)
        lang = self.p.language
        if lang == "python":
            script = self._shell_prelude() + f".venv/bin/python -m pip install --no-input {quoted}"
        elif lang == "javascript":
            if self.p.fs.exists("package.json") != "file":
                self._write_hidden("package.json", json.dumps({"name": "project", "version": "1.0.0", "private": True}, indent=2).encode() + b"\n")
            script = f"npm install --no-audit --no-fund --no-progress --loglevel=error {quoted}"
        else:
            raise JobError("Package installation is available for Python and JavaScript projects.")
        await self._system(f"$ {script.splitlines()[-1]}\n")
        result, text = await self._exec("install", ["bash", "-c", script], self._limits("install"), network="install")
        await self._finish_phase("install", result, text)
        if result.reason == "ok" and lang == "python":
            self._sync_requirements(pkgs)
        return result, "install"

    def _sync_requirements(self, pkgs: list[str]) -> None:
        current = (self._read_hidden("requirements.txt") or b"").decode("utf-8", "replace")
        have = {re.split(r"[<>=!~\[; ]", ln.strip(), maxsplit=1)[0].lower().replace("_", "-") for ln in current.splitlines() if ln.strip() and not ln.startswith("#")}
        add = [p for p in pkgs if re.split(r"[<>=!~\[; ]", p, maxsplit=1)[0].lower().replace("_", "-") not in have]
        if add:
            body = current.rstrip("\n") + ("\n" if current.strip() else "") + "\n".join(add) + "\n"
            self._write_hidden("requirements.txt", body.encode())
        # The venv now matches requirements.txt, so skip a redundant reinstall on next run.
        self._write_hidden(".compieler/req.sha", _sha(self._read_hidden("requirements.txt") or b"").encode())
